#!/usr/bin/env python
"""Natural Earth 1:110m 육지(TopoJSON) → 정거원통도법 SVG path 조각(templates/_land.html).

연구 지역 레이더 지도(region_map 매크로)가 이 조각을 그대로 포함한다. 런타임 라이브러리·외부 요청이 없다.
좌표계: x = 경도 + 180 (0–360), y = 90 − 위도 (0–180). 태평양 중심 화면은 매크로에서 같은 path를 x+360으로 한 번 더 그린다(남극은 뺀다).

사용(한 번만, 결과 파일을 저장소에 둔다):
  python themes/t4.v02/tools/land_to_svg.py <land-110m.json 또는 world-atlas를 감싼 .js>
  예) python themes/t4.v02/tools/land_to_svg.py themes/t8_globe/assets/vendor/world-110m.js

자료: Natural Earth (public domain) · world-atlas@2 land-110m TopoJSON (Mike Bostock, ISC).
"""
import json
import re
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / 'templates' / '_land.html'


def load(path):
    text = Path(path).read_text(encoding='utf-8')
    if not text.lstrip().startswith('{'):                  # window.X = {...};
        text = text[text.index('{'):text.rindex('}') + 1]
    return json.loads(text)


def decode_arcs(topo):
    sx, sy = topo['transform']['scale']
    tx, ty = topo['transform']['translate']
    out = []
    for arc in topo['arcs']:
        x = y = 0
        pts = []
        for dx, dy in arc:
            x += dx
            y += dy
            pts.append((x * sx + tx, y * sy + ty))
        out.append(pts)
    return out


def ring_coords(ring, arcs):
    pts = []
    for i in ring:
        a = arcs[i] if i >= 0 else arcs[~i][::-1]
        pts.extend(a if not pts else a[1:])
    # 날짜변경선을 넘는 고리(추코트카·피지 등)는 경도를 이어 붙여(±360) 화면을 가로지르는 선을 막는다
    out = []
    for lon, lat in pts:
        if out:
            while lon - out[-1][0] > 180:
                lon -= 360
            while lon - out[-1][0] < -180:
                lon += 360
        out.append((lon, lat))
    return out


def path_d(rings):
    """상대 좌표 l 명령으로 짧게 쓴다(소수 1자리, 같은 점은 건너뜀)."""
    parts = []
    for ring in rings:
        q = [(round(lon + 180, 1), round(90 - lat, 1)) for lon, lat in ring]
        if len(q) < 3:
            continue
        cmds = [f'M{q[0][0]:g} {q[0][1]:g}']
        px, py = q[0]
        for x, y in q[1:]:
            dx, dy = round(x - px, 1), round(y - py, 1)
            if dx == 0 and dy == 0:
                continue
            cmds.append(f'{dx:g} {dy:g}')
            px, py = x, y
        parts.append(cmds[0] + 'l' + ' '.join(cmds[1:]) + 'z')
    d = ''.join(parts)
    d = re.sub(r'(?<![\d.])0\.', '.', d)                # 0.5 → .5, -0.3 → -.3
    return re.sub(r' -', '-', d)


def main():
    topo = load(sys.argv[1])
    arcs = decode_arcs(topo)
    rings = []
    for g in topo['objects']['land']['geometries']:
        polys = g['arcs'] if g['type'] == 'MultiPolygon' else [g['arcs']]
        for poly in polys:
            for ring in poly:
                rc = ring_coords(ring, arcs)
                if max(lat for _, lat in rc) < -55:      # 남극(지도 범위 밖, 극을 도는 고리)
                    continue
                rings.append(rc)
    d = path_d(rings)
    OUT.write_text('{# Natural Earth 1:110m land (public domain), world-atlas@2 TopoJSON (ISC). '
                   'Generated by themes/t4.v02/tools/land_to_svg.py — do not edit by hand. #}\n'
                   f'<path id="land-110m" d="{d}"/>\n', encoding='utf-8')
    print(f'{OUT}: {len(rings)} rings, {len(d):,} chars')


if __name__ == '__main__':
    main()
