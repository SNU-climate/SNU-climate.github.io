#!/usr/bin/env python
"""NASA GISTEMP v4 전지구 연평균 기온 편차(CSV) → assets/data/gistemp.js (warming stripes용 JS 상수).

사용(테마 폴더 밖 어디서든):
  curl -sSL -o /tmp/GLB.csv https://data.giss.nasa.gov/gistemp/tabledata_v4/GLB.Ts+dSST.csv
  python themes/t4_dashboard/tools/gistemp_to_js.py /tmp/GLB.csv
연평균(J-D)이 '***'인 해(진행 중인 해)는 넣지 않는다. 편차 기준은 1951–1980 평균.
"""
import csv
import datetime as dt
import json
import sys
from pathlib import Path

URL = 'https://data.giss.nasa.gov/gistemp/tabledata_v4/GLB.Ts+dSST.csv'
OUT = Path(__file__).resolve().parent.parent / 'assets' / 'data' / 'gistemp.js'


def main(src):
    rows = list(csv.reader(open(src, encoding='utf-8')))
    head = next(i for i, r in enumerate(rows) if r and r[0] == 'Year')
    col = rows[head].index('J-D')
    years, anom = [], []
    for r in rows[head + 1:]:
        if not r or not r[0].isdigit() or len(r) <= col or '*' in r[col]:
            continue
        years.append(int(r[0]))
        anom.append(round(float(r[col]), 2))
    if any(b - a != 1 for a, b in zip(years, years[1:])):
        raise SystemExit('연도가 연속되지 않음')
    data = {
        'source': 'NASA GISS Surface Temperature Analysis (GISTEMP v4)',
        'url': URL,
        'series': 'Global mean land-ocean temperature index, annual mean (J-D)',
        'baseline': '1951-1980',
        'unit': 'degC',
        'retrieved': dt.date.today().isoformat(),
        'start': years[0],
        'end': years[-1],
        'anom': anom,
    }
    OUT.write_text('/* NASA GISTEMP v4 (GLB.Ts+dSST), annual J-D anomaly vs 1951-1980, degC.\n'
                   '   Generated by themes/t4_dashboard/tools/gistemp_to_js.py — do not edit by hand. */\n'
                   'window.GISTEMP = ' + json.dumps(data, separators=(',', ':')) + ';\n', encoding='utf-8')
    print(f'{OUT}: {years[0]}–{years[-1]} ({len(years)} yr), min {min(anom)}, max {max(anom)}')


if __name__ == '__main__':
    main(sys.argv[1] if len(sys.argv) > 1 else 'GLB.Ts+dSST.csv')
